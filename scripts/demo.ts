import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const demo = join(root, "demo");

/** Component pages in site order; the kitchen sink and the site checks are generated from this list. */
export const components = ["typography", "links-buttons", "forms", "content", "navigation", "overlays", "feedback"];

/** Layout pages in gallery order, under demo/layouts/. */
export const layouts = ["docs", "article", "login", "pricing", "settings"];

/** Themed showcase pages in gallery order, under demo/showcase/; each carries its own theme and skips settings. */
export const showcase = ["editorial", "console", "playful"];

/** Every demo page, for checks that cover the whole site. */
export const pages = [
  "/demo/",
  "/demo/theming.html",
  ...components.map((name) => `/demo/components/${name}.html`),
  "/demo/kitchen-sink.html",
  "/demo/layouts/",
  ...layouts.map((name) => `/demo/layouts/${name}.html`),
  "/demo/showcase/",
  ...showcase.map((name) => `/demo/showcase/${name}.html`),
];

interface Section {
  id: string;
  title: string;
  markup: string[];
}

interface Page {
  name: string;
  title: string;
  sections: Section[];
}

/** Rewrites a component page's relative URL so it resolves from demo/, where the kitchen sink lives. */
function relocate(url: string) {
  if (/^(#|[a-z]+:|\/)/i.test(url)) return url;
  const { pathname, search, hash } = new URL(url, "https://demo.invalid/demo/components/");
  return (pathname.replace(/^\/demo\//, "") || "./") + search + hash;
}

/**
 * Reads the examples from a Prettier-formatted component page: sections sit at 6 spaces and their
 * `figure[data-example]` at 8, so a figure's own closing tag is the first `</figure>` at 8 spaces.
 */
async function read(name: string): Promise<Page> {
  const lines = (await readFile(join(demo, "components", `${name}.html`), "utf8")).split("\n");
  const title = lines.join("\n").match(/<h1>(.*?)<\/h1>/)?.[1] ?? name;
  const sections: Section[] = [];
  let section: Section | undefined;
  let figure: string[] | undefined;
  for (const line of lines) {
    const opened = line.match(/^ {6}<section id="([^"]+)"/);
    if (opened) section = { id: opened[1], title: "", markup: [] };
    else if (section && /^ {6}<\/section>/.test(line)) {
      if (section.markup.length > 0) sections.push(section);
      section = undefined;
    } else if (section && !section.title) section.title = line.match(/<h2[^>]*>(.*?)<\/h2>/)?.[1] ?? "";
    if (!section) continue;
    if (/^ {8}<figure data-example=/.test(line)) figure = [];
    else if (figure && /^ {8}<\/figure>/.test(line)) {
      section.markup.push(...figure);
      figure = undefined;
    } else if (figure)
      figure.push(line.replace(/(href|src)="([^"]*)"/g, (_, attribute, url) => `${attribute}="${relocate(url)}"`));
  }
  return { name, title, sections };
}

export async function generate() {
  const sources = await Promise.all(components.map(read));

  const ids = new Map<string, string>();
  for (const page of sources) {
    for (const section of page.sections) {
      const found = [
        section.id,
        ...Array.from(section.markup.join("\n").matchAll(/\sid="([^"]+)"/g), (match) => match[1]),
      ];
      for (const id of found) {
        const other = ids.get(id);
        if (other) throw new Error(`Duplicate id "${id}" in ${other} and ${page.name}.html`);
        ids.set(id, `${page.name}.html`);
      }
    }
  }

  const sideNav = sources
    .map(
      (page) => `        <li>
          ${page.title}
          <ul>
${page.sections.map((section) => `            <li><a href="#${section.id}">${section.title}</a></li>`).join("\n")}
          </ul>
        </li>`,
    )
    .join("\n");

  const main = sources
    .map(
      (page) => `      <section aria-labelledby="${page.name}-page-title">
        <h2 id="${page.name}-page-title"><a href="components/${page.name}.html">${page.title}</a></h2>
${page.sections
  .map(
    (section) => `        <section id="${section.id}">
          <h3>${section.title}</h3>
${section.markup.join("\n")}
        </section>`,
  )
  .join("\n")}
      </section>`,
    )
    .join("\n");

  const html = `<!doctype html>
<!-- Generated by scripts/demo.ts from demo/components/*.html. Edit the component pages instead. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Kitchen sink · m.css</title>
    <link rel="stylesheet" href="../dist/m.css" />
    <link rel="stylesheet" href="assets/demo.css" />
    <script src="assets/demo.js"></script>
  </head>
  <body>
    <header>
      <nav aria-label="Site">
        <ul>
          <li><strong>m.css</strong></li>
        </ul>
        <ul>
          <li><a href="./">Home</a></li>
          <li><a href="theming.html">Theming</a></li>
          <li><a href="components/typography.html" aria-current="true">Components</a></li>
          <li><a href="layouts/">Layouts</a></li>
          <li><a href="showcase/">Showcase</a></li>
          <li><a href="https://github.com/abraham/m.css">GitHub</a></li>
        </ul>
      </nav>
      <h1>Kitchen sink</h1>
      <p>Every example from the component pages on one page, with no demo controls.</p>
    </header>

    <nav aria-label="Sections">
      <ul>
${sideNav}
      </ul>
    </nav>

    <main>
${main}
    </main>

    <footer>
      <p><a href="https://www.npmjs.com/package/@abraham/m.css">@abraham/m.css</a></p>
    </footer>
  </body>
</html>
`;
  await writeFile(join(demo, "kitchen-sink.html"), html);
}

if (import.meta.main) await generate();
